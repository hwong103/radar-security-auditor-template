import { findingMarker } from "./findings.js";
import type {
  Finding,
  PublicationPlan,
  PullRequest,
  RepositoryConfig,
  RepositoryIssue,
} from "./types.js";

export interface ExistingState {
  readonly issues: readonly RepositoryIssue[];
  readonly pullRequests: readonly PullRequest[];
  readonly trustedIssueAuthor?: string | null;
}

export function issueTitle(finding: Finding): string {
  return `[security] ${finding.aliases[0] ?? finding.identity}: ${finding.package.name}`;
}

export function issueBody(
  finding: Finding,
  modelSummary = finding.modelAdvice?.summary,
): string {
  const patched = finding.package.firstPatchedVersion
    ? `| First patched version | \`${inline(finding.package.firstPatchedVersion)}\` |`
    : "| First patched version | Not reported by GitHub |";
  return [
    findingMarker(finding.key),
    `## ${escapeMarkdown(finding.summary)}`,
    modelSummary ? escapeMarkdown(modelSummary) : "",
    "| Field | Value |",
    "| --- | --- |",
    `| Severity | ${finding.severity} |`,
    `| Advisory | ${finding.aliases.map((alias) => `[${escapeMarkdown(alias)}](${finding.htmlUrl})`).join(", ")} |`,
    `| Ecosystem | ${finding.package.ecosystem} |`,
    `| Package | \`${inline(finding.package.name)}\` |`,
    `| Manifest | \`${inline(finding.package.manifestPath ?? "unknown")}\` |`,
    `| Vulnerable range | \`${inline(finding.package.vulnerableVersionRange ?? "unknown")}\` |`,
    patched,
    finding.radarUrl ? `| Radar record | ${finding.radarUrl} |` : "",
    "",
    "## Remediation",
    "1. Upgrade the affected package to the listed patched version or a later compatible version.",
    "2. Run the repository's package update, tests, and security checks.",
    "3. Review package-manager and release-note changes before merging.",
    "",
    "This issue is maintained from GitHub's authoritative Dependabot alert. Cloudflare Radar is discovery and enrichment. Feed prose is untrusted and is never used as proof that this repository is affected.",
    "",
    "_Generated by Radar Security Auditor. No automated merge._",
  ]
    .filter(Boolean)
    .join("\n");
}

function inline(value: string): string {
  return value.replaceAll("`", "'").replace(/[\r\n]+/g, " ");
}

function escapeMarkdown(value: string): string {
  return inline(value).replace(/([\\*_{}[\]()<>#+.!|-])/g, "\\$1");
}

export function planPublications(
  finding: Finding,
  repository: RepositoryConfig,
  state: ExistingState,
): PublicationPlan {
  if (!repository.publishIssues) {
    return {
      action: "report-only",
      reason: "Issue publication is not enabled for this repository.",
      finding,
      issueNumber: null,
      pullRequestNumber: null,
      branch: null,
    };
  }
  const marker = findingMarker(finding.key);
  const matchingIssues = state.issues.filter(
    (issue) =>
      issue.body.includes(marker) &&
      typeof state.trustedIssueAuthor === "string" &&
      issue.authorLogin === state.trustedIssueAuthor &&
      issue.authorType?.toLowerCase() === "bot",
  );
  const existingIssue =
    matchingIssues.find((issue) => issue.state === "open") ?? matchingIssues[0];
  if (existingIssue?.state === "open") {
    return {
      action: "update-issue",
      reason: "An open marker-matched issue already tracks this finding.",
      finding,
      issueNumber: existingIssue.number,
      pullRequestNumber: null,
      branch: null,
    };
  }
  if (existingIssue?.state === "closed") {
    return {
      action: "report-only",
      reason:
        "The matching issue was closed. A new later advisory must get a new finding key.",
      finding,
      issueNumber: existingIssue.number,
      pullRequestNumber: null,
      branch: null,
    };
  }
  const existingPr = state.pullRequests.find(
    (pullRequest) =>
      pullRequest.state === "open" &&
      (pullRequest.body.includes(marker) || isDependabotPullRequest(pullRequest, finding)),
  );
  if (existingPr) {
    return {
      action: "reuse-pr",
      reason: "An open matching or Dependabot pull request already exists.",
      finding,
      issueNumber: null,
      pullRequestNumber: existingPr.number,
      branch: existingPr.headRef,
    };
  }
  if (repository.openDraftPrs && repository.allowDependencyChanges) {
    return {
      action: "create-issue",
      reason:
        "Draft replacement PRs remain disabled until a tested dependency updater and credential-free validation path exist.",
      finding,
      issueNumber: null,
      pullRequestNumber: null,
      branch: null,
    };
  }
  return {
    action: "create-issue",
    reason: "Draft PR publishing is disabled or requires opt-in for this repository.",
    finding,
    issueNumber: null,
    pullRequestNumber: null,
    branch: null,
  };
}

function isDependabotPullRequest(pullRequest: PullRequest, finding: Finding): boolean {
  if (!pullRequest.headRef.startsWith("dependabot/")) return false;
  const title = pullRequest.title.toUpperCase();
  const body = pullRequest.body.toUpperCase();
  const packageName = finding.package.name.toUpperCase();
  return finding.aliases.some(
    (alias) => title.includes(packageName) && body.includes(alias.toUpperCase()),
  );
}

export function summarizePlans(plans: readonly PublicationPlan[]): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const plan of plans) counts[plan.action] = (counts[plan.action] ?? 0) + 1;
  return counts;
}

export function safeRepositoryPath(packageName: string): boolean {
  return (
    packageName.length > 0 &&
    packageName.length <= 214 &&
    !packageName.startsWith(".") &&
    !packageName.includes("\\") &&
    !packageName.includes("\0")
  );
}
